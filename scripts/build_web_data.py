#!/usr/bin/env python3
"""Write data/tprm.js for the web app from the single source of truth in build_template.py.

Usage:  python scripts/build_web_data.py
The file is generated; CI fails if it drifts from the build script.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_template as bt  # noqa: E402

dom_name = dict(bt.DOMAINS)
data = {
    "factors": {
        "data": bt.DATA_CLASS, "crit": bt.CRITICALITY, "access": bt.ACCESS, "ai": bt.AI_USE,
    },
    "tier1Min": bt.TIER1_MIN,
    "tier2Min": bt.TIER2_MIN,
    "cadence": bt.CADENCE_MONTHS,
    "bands": bt.SCORE_BANDS,
    "residual": bt.RESIDUAL,
    "categories": bt.CATEGORIES,
    "statusInventory": bt.STATUS_INV,
    "statusAssessment": bt.STATUS_ASSESS,
    "answers": bt.ANSWERS,
    "domains": [{"code": c, "name": n} for c, n in bt.DOMAINS],
    "questions": [{"id": q, "domain": d, "text": t, "weight": w, "evidence": e} for q, d, t, w, e in bt.QUESTIONS],
    "clauses": [{"id": i, "clause": c, "why": w, "Tier 1": t1, "Tier 2": t2, "Tier 3": t3} for i, c, w, t1, t2, t3 in bt.CLAUSES],
    "clauseLevels": bt.CLAUSE_LEVELS,
    "vendors": [
        {"id": v[0], "name": v[1], "service": v[2], "category": v[3], "owner": v[4], "data": v[5], "crit": v[6],
         "access": v[7], "ai": v[8], "location": v[9], "contractEnd": v[10].isoformat(), "status": v[11], "notes": v[12]}
        for v in bt.VENDORS
    ],
    "sample": {"vendor": bt.SAMPLE_VENDOR, "date": "2026-10-12", "assessor": "Security Analyst, GRC team",
               "answers": bt.SAMPLE_ANSWERS, "comments": bt.SAMPLE_COMMENTS},
}
out = Path(__file__).resolve().parent.parent / "data" / "tprm.js"
out.parent.mkdir(exist_ok=True)
body = json.dumps(data, ensure_ascii=False, indent=1)
out.write_text("/* Generated by scripts/build_web_data.py from scripts/build_template.py. Do not edit. MIT License. */\n"
               "window.TPRM = " + body + ";\n", encoding="utf-8", newline="\n")
print(f"Wrote {out} ({len(data['questions'])} questions, {len(data['clauses'])} clauses, {len(data['vendors'])} sample vendors)")
